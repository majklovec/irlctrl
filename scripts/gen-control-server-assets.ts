// Build and embed the control-server browser UI for the compiled binary.
import { Buffer } from "node:buffer";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { PAGES, type PageName } from "../src/control-server/pages";

const outputFile = fileURLToPath(
    new URL(
        "../src/control-server/.generated.frontend-assets.ts",
        import.meta.url,
    ),
);

await Bun.$`bun scripts/gen-modules.ts`.quiet();

const result = await Bun.build({
    entrypoints: PAGES.map(
        (name) =>
            new URL(`../public/${name}.html`, import.meta.url).pathname,
    ),
    target: "browser",
    minify: true,
    splitting: true,
    publicPath: "/assets/",
    naming: {
        asset: "[name]-[hash].[ext]",
        chunk: "[name]-[hash].[ext]",
        entry: "[name]-[hash].[ext]",
    },
});
if (!result.success) {
    for (const log of result.logs) console.error(log);
    throw new Error("Failed to bundle the control-server web UI");
}

const pages = {} as Record<PageName, string>;
const assets: Record<string, { type: string; base64: string }> = {};
for (const output of result.outputs) {
    const file = output.path.replace(/^\.\//, "");
    const page = PAGES.find(
        (name) => file.startsWith(`${name}-`) && file.endsWith(".html"),
    );
    if (page) {
        pages[page] = await output.text();
    } else {
        assets[file] = {
            type: output.type,
            base64: Buffer.from(await output.arrayBuffer()).toString("base64"),
        };
    }
}

for (const page of PAGES) {
    if (!pages[page])
        throw new Error(`The control-server UI build omitted ${page}.html`);
}

const source = `// AUTO-GENERATED by scripts/gen-control-server-assets.ts — do not edit.\nexport default ${JSON.stringify({ pages, assets })};\n`;
let previous = "";
try {
    previous = await readFile(outputFile, "utf8");
} catch (error) {
    if (!(error instanceof Error) || !("code" in error) || error.code !== "ENOENT")
        throw error;
}
if (source !== previous) await writeFile(outputFile, source);
console.log(
    `[gen-control-server-assets] embedded ${PAGES.length} pages and ${Object.keys(assets).length} assets`,
);
