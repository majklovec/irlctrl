// Build and embed the control-server browser UI for the compiled binary.
import { Buffer } from "node:buffer";
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { frontendPageEntries } from "../shared/frontend";

const outputFile = fileURLToPath(
	new URL("../generated/frontend-assets.ts", import.meta.url),
);
await mkdir(new URL("../generated/", import.meta.url), { recursive: true });

await Bun.$`bun scripts/gen-modules.ts`.quiet();
const pagesToBuild = frontendPageEntries(
	new URL("../frontend/", import.meta.url),
);

const result = await Bun.build({
	entrypoints: pagesToBuild.map((entry) => entry.path),
	target: "browser",
	minify: true,
	splitting: true,
	publicPath: "/assets/",
	naming: {
		asset: "[name]-[hash].[ext]",
		chunk: "[name]-[hash].[ext]",
		entry: "[name]-[hash].[ext]",
	},
});
if (!result.success) {
	for (const log of result.logs) console.error(log);
	throw new Error("Failed to bundle the control-server web UI");
}

const pages: Record<string, string> = {};
const assets: Record<string, { type: string; base64: string }> = {};
for (const output of result.outputs) {
	const file = output.path.replace(/^\.\//, "");
	const page = pagesToBuild.find(
		({ name }) => file.startsWith(`${name}-`) && file.endsWith(".html"),
	);
	if (page) {
		pages[page.name] = await output.text();
	} else {
		assets[file] = {
			type: output.type,
			base64: Buffer.from(await output.arrayBuffer()).toString("base64"),
		};
	}
}

for (const { name } of pagesToBuild)
	if (!pages[name]) throw new Error(`The frontend build omitted ${name}.html`);

const source = `// AUTO-GENERATED by scripts/gen-control-server-assets.ts — do not edit.\nexport default ${JSON.stringify({ pages, assets })};\n`;
let previous = "";
try {
	previous = await readFile(outputFile, "utf8");
} catch (error) {
	if (
		!(error instanceof Error) ||
		!("code" in error) ||
		error.code !== "ENOENT"
	)
		throw error;
}
if (source !== previous) await writeFile(outputFile, source);
console.log(
	`[gen-control-server-assets] embedded ${pagesToBuild.length} pages and ${Object.keys(assets).length} assets`,
);
