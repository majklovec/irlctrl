/*
 * Build-time generated page manifests (scripts/gen_pages.ts).
 *
 * Emits two manifests, one static import per page (sorted for
 * deterministic output):
 *
 *   generated/pages.ts                        — one import per
 *   server/pages/<id>/frontend/menu.ts, exporting the MenuContribution
 *   list MENUS. The browser bundle (the shell nav) resolves everything
 *   statically from this manifest — never a runtime readdir.
 *   generated/pages.server.ts               — one import per
 *   server/pages/<id>/index.ts, exporting the full PageModule list
 *   PAGE_MODULES; used by the compiled binary (bun build --compile),
 *   where the runtime directory scan in core/registry.ts cannot reach
 *   disk (import.meta.url lives in Bun's virtual /$bunfs mount).
 *
 * The browser manifest carries menus only — deliberately no page
 * components — so a page bundle never drags in the other pages'
 * client code. Runs in Bun (not the browser) and is re-invoked by the
 * entrypoints, the web-UI bundling and package.json `predev`/`pretest`/
 * `prebuild:*`; only rewrites a file when the output actually changes
 * so watch loops don't churn it.
 */
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { PAGES_ROOT } from "../shared/paths";

const baseDir = fileURLToPath(new URL("..", import.meta.url));
const generatedDir = fileURLToPath(
    new URL("../generated/", import.meta.url),
);
await mkdir(generatedDir, { recursive: true });

const menus: string[] = [];
for await (const p of new Bun.Glob(`${PAGES_ROOT}/*/frontend/menu.ts`).scan({
    cwd: baseDir,
}))
    menus.push(p);
menus.sort();

const menusSource = [
    "// AUTO-GENERATED by scripts/gen_pages.ts — do not edit.",
    "// One static import per server/pages/<id>/frontend/menu.ts: the browser menu manifest (MENUS).",
    ...menus.map(
        (p, i) =>
            `import menu${i} from "../${p.slice(0, -".ts".length)}";`,
    ),
    "",
    `export const MENUS = [${menus.map((_, i) => `menu${i}`).join(", ")}];`,
    "",
].join("\n");

const pageModules: string[] = [];
for await (const p of new Bun.Glob(`${PAGES_ROOT}/*/index.ts`).scan({
    cwd: baseDir,
}))
    pageModules.push(p);
pageModules.sort();

const serverSource = [
    "// AUTO-GENERATED by scripts/gen_pages.ts — do not edit.",
    "// One static import per server/pages/<id>/index.ts: the PageModule list (PAGE_MODULES) for the compiled binaries.",
    ...pageModules.map(
        (p, i) =>
            `import page${i} from "../${p.slice(0, -".ts".length)}";`,
    ),
    "",
    `export const PAGE_MODULES = [${pageModules.map((_, i) => `page${i}`).join(", ")}];`,
    "",
].join("\n");

const outputs: [string, string][] = [
    [join(generatedDir, "pages.ts"), menusSource],
    [join(generatedDir, "pages.server.ts"), serverSource],
];

for (const [file, source] of outputs) {
    let previous = "";
    try {
        previous = await readFile(file, "utf8");
    } catch (error) {
        if (!(error instanceof Error && "code" in error && error.code === "ENOENT"))
            throw error;
    }
    if (source !== previous) await writeFile(file, source);
}
console.log(
    `[gen-pages] ${menus.length} menu(s), ${pageModules.length} page module(s)`,
);
