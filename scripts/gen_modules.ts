// Build-time generated module manifests.
//
// Emits three manifests, one static import per module (sorted for
// deterministic output), default-exporting the registrations as an array.
// Each file lists paths only — it never imports a module — so a broken module
// cannot break the generator:
//
// Modules live under the roots listed in shared/paths.ts (MODULE_ROOTS:
// client/modules plus the page slices' server/pages/<page>/modules); every
// manifest spans all of them.
//
//   generated/modules.frontend.ts — one import per <root>/<id>/frontend.tsx;
//   the browser bundle statically resolves every import (no runtime Glob).
//   generated/modules.settings.ts — one import per <root>/<id>/settings.tsx;
//   the settings framework (client/frontend/modules.tsx) registers each module's
//   settings card from this manifest.
//   generated/overlay_schemas.ts  — one import per <root>/<id>/overlay_schema.ts
//   (overlay element schemas, used by the scene validator on both sides).
//   generated/overlay_elements.ts — one import per <root>/<id>/overlay_elements.tsx
//   (the browser half of the overlay elements: rendering + inspector).
//   generated/modules.backend.ts  — one import per <root>/<id>/backend.ts;
//   used by the compiled binaries (bun build --compile), where the runtime
//   directory scan in shared/registry.ts cannot reach disk (import.meta.url
//   lives in Bun's virtual /$bunfs mount).
//   generated/role_diagrams.ts    — the <root>/<id>/role_<role>.svg architecture
//   diagrams as URL assets keyed by role id; the device setup wizard shows
//   the diagram in the card of the role it illustrates.
//   generated/version.ts — the package.json version for the UI footer.
//   generated/i18n.ts — every catalog (i18n/<lang>.json plus each
//   <root>/<id>/i18n/<lang>.json) inlined per language, for the compiled
//   binaries (shared/i18n.ts merges them; unbundled runs scan the disk).
//   generated/migrations.ts — the control server's server/core/migrations/*.sql
//   files inlined as name→SQL, for the compiled binaries (server/core/db.ts
//   applies them from disk when unbundled).
//
// Runs in Bun (not the browser) and is re-invoked by server.ts before it
// bundles the web UI, plus by package.json `predev`/`pretest` and the release
// workflow before the compiled builds. Regenerated on demand; only rewrites a
// file when the output actually changes so watch loops don't churn it.

import { mkdir, readFile, writeFile } from "node:fs/promises";
import { sep } from "node:path";
import { fileURLToPath } from "node:url";
import { CORE_I18N_DIR, MIGRATIONS_DIR, MODULE_ROOTS } from "../shared/paths";

// The app dir is the scan base so the relative patterns below resolve the
// same way regardless of the CWD.
const baseDir = fileURLToPath(new URL("..", import.meta.url));
const generatedDir = fileURLToPath(new URL("../generated/", import.meta.url));
await mkdir(generatedDir, { recursive: true });

interface ManifestSpec {
    outFile: string; // fileURLToPath'ed output path
    file: string; // the per-module file to collect, e.g. frontend.tsx
    variable: string; // import base name, e.g. m / b
    purpose: string; // header line describing the manifest
}

async function buildManifest(spec: ManifestSpec): Promise<void> {
    const matches: string[] = [];
    for (const root of MODULE_ROOTS)
        for await (const p of new Bun.Glob(`${root}/*/${spec.file}`).scan({
            cwd: baseDir,
        }))
            matches.push(p.split(sep).join("/"));
    matches.sort();

    const lines = [
        "// AUTO-GENERATED by scripts/gen_modules.ts — do not edit.",
        `// ${spec.purpose}`,
        "// One static import per matching module, in sorted path order.",
        "",
    ];

    matches.forEach((path, i) => {
        // Generated files live in generated/, so imports step back to the app dir.
        const specifier = path.replace(/\.(tsx?|js)$/, "");
        lines.push(`import ${spec.variable}${i} from "../${specifier}";`);
    });

    lines.push("");
    lines.push(
        matches.length
            ? `export default [${[...Array(matches.length)].map((_, i) => `${spec.variable}${i}`).join(", ")}] as unknown[];`
            : "export default [] as unknown[];",
        "",
    );

    await writeIfChanged(spec.outFile, lines.join("\n"));
    console.log(
        `[gen_modules] ${spec.outFile.split(sep).pop()} → ${matches.length} ${spec.file} module(s)`,
    );
}

/** Write `outFile` only when its content changed (keeps watch loops quiet). */
async function writeIfChanged(outFile: string, next: string): Promise<void> {
    let prev = "";
    try {
        prev = await readFile(outFile, "utf8");
    } catch {
        /* missing — will write */
    }
    if (next !== prev) await writeFile(outFile, next);
}

/** generated/i18n.ts: per language, the core catalog followed by each module's. */
async function buildI18nManifest(): Promise<void> {
    const files: string[] = [];
    // Glob yields OS separators; normalise so the language key and the
    // import specifiers come out identical on Windows.
    for (const pattern of [
        `${CORE_I18N_DIR}/*.json`,
        ...MODULE_ROOTS.map((root) => `${root}/*/i18n/*.json`),
    ])
        for await (const p of new Bun.Glob(pattern).scan({ cwd: baseDir }))
            files.push(p.split(sep).join("/"));
    files.sort();
    const byLang = new Map<string, string[]>();
    files.forEach((path, i) => {
        const lang = path.slice(path.lastIndexOf("/") + 1, -".json".length);
        const list = byLang.get(lang) ?? [];
        list.push(`c${i}`);
        byLang.set(lang, list);
    });
    const lines = [
        "// AUTO-GENERATED by scripts/gen_modules.ts — do not edit.",
        "// Every i18n catalog (core, then each module's) per language, for the compiled binaries.",
        "",
        ...files.map((path, i) => `import c${i} from "../${path}";`),
        "",
        "export default {",
        ...[...byLang.entries()]
            .sort(([a], [b]) => a.localeCompare(b))
            .map(([lang, names]) => `\t${lang}: [${names.join(", ")}],`),
        "} as Record<string, Record<string, string>[]>;",
        "",
    ];
    await writeIfChanged(
        fileURLToPath(new URL("../generated/i18n.ts", import.meta.url)),
        lines.join("\n"),
    );
    console.log(
        `[gen_modules] i18n.ts → ${files.length} catalog(s) in ${byLang.size} language(s)`,
    );
}

/** generated/migrations.ts: every server/core/migrations/*.sql file inlined as name→SQL, in file-name order. */
async function buildMigrationsManifest(): Promise<void> {
    const files: string[] = [];
    for await (const p of new Bun.Glob(`${MIGRATIONS_DIR}/*.sql`).scan({
        cwd: baseDir,
    }))
        files.push(p.split(sep).join("/"));
    files.sort();
    const lines = [
        "// AUTO-GENERATED by scripts/gen_modules.ts — do not edit.",
        `// ${MIGRATIONS_DIR}/*.sql inlined as name → SQL text, for the compiled binaries.`,
        "export default {",
        // Keys are the file names themselves: schema_migrations tracks them
        // verbatim, so manifest entries must match what a source run recorded.
        ...(await Promise.all(
            files.map(async (path) => {
                const name = path.split("/").pop()!;
                const sql = await Bun.file(
                    new URL(`../${path}`, import.meta.url),
                ).text();
                return `\t${JSON.stringify(name)}: ${JSON.stringify(sql)},`;
            }),
        )),
        "} as Record<string, string>;",
        "",
    ];
    await writeIfChanged(
        fileURLToPath(new URL("../generated/migrations.ts", import.meta.url)),
        lines.join("\n"),
    );
    console.log(
        `[gen_modules] migrations.ts → ${files.length} migration(s)`,
    );
}

/** generated/version.ts: the package.json version (the UI footer; keeps package.json out of the bundle). */
/** generated/role_diagrams.ts: each module's role_<role>.svg architecture diagram as a URL asset, for the device setup wizard. */
async function buildRoleDiagramsManifest(): Promise<void> {
    const matches: string[] = [];
    for (const root of MODULE_ROOTS)
        for await (const p of new Bun.Glob(`${root}/*/role_*.svg`).scan({
            cwd: baseDir,
        }))
            matches.push(p.split(sep).join("/"));
    matches.sort();
    const roleOf = (path: string) => path.match(/role_(.+)\.svg$/)?.[1] ?? "";
    const lines = [
        "// AUTO-GENERATED by scripts/gen_modules.ts — do not edit.",
        "// Each module's role architecture diagram (role_<role>.svg) as a URL asset, keyed by role id.",
        "",
        ...matches.map((path, i) => `import d${i} from "../${path}";`),
        "",
        "export default {",
        ...matches.map(
            (path, i) => `\t${JSON.stringify(roleOf(path))}: d${i},`,
        ),
        "} as Record<string, string>;",
        "",
    ];
    await writeIfChanged(
        fileURLToPath(new URL("../generated/role_diagrams.ts", import.meta.url)),
        lines.join("\n"),
    );
    console.log(
        `[gen_modules] role_diagrams.ts → ${matches.length} diagram(s)`,
    );
}

async function buildVersion(): Promise<void> {
    const { version } = (await Bun.file(
        new URL("../package.json", import.meta.url),
    ).json()) as {
        version: string;
    };
    await writeIfChanged(
        fileURLToPath(new URL("../generated/version.ts", import.meta.url)),
        [
            "// AUTO-GENERATED by scripts/gen_modules.ts — do not edit.",
            `export const APP_VERSION = ${JSON.stringify(version)};`,
            "",
        ].join("\n"),
    );
}

await Promise.all([
    buildVersion(),
    buildI18nManifest(),
    buildRoleDiagramsManifest(),
    buildMigrationsManifest(),
    buildManifest({
        outFile: fileURLToPath(
            new URL("../generated/modules.frontend.ts", import.meta.url),
        ),
        file: "frontend.tsx",
        variable: "m",
        purpose:
            "one static import per <root>/<id>/frontend.tsx; the browser bundle never uses Glob",
    }),
    buildManifest({
        outFile: fileURLToPath(
            new URL("../generated/modules.settings.ts", import.meta.url),
        ),
        file: "settings.tsx",
        variable: "s",
        purpose:
            "one static import per <root>/<id>/settings.tsx; the settings framework registers each module's settings card from this manifest",
    }),
    buildManifest({
        outFile: fileURLToPath(
            new URL("../generated/overlay_schemas.ts", import.meta.url),
        ),
        file: "overlay_schema.ts",
        variable: "o",
        purpose:
            "one static import per <root>/<id>/overlay_schema.ts; the overlay scene validator resolves element types through these",
    }),
    buildManifest({
        outFile: fileURLToPath(
            new URL("../generated/overlay_elements.ts", import.meta.url),
        ),
        file: "overlay_elements.tsx",
        variable: "e",
        purpose:
            "one static import per <root>/<id>/overlay_elements.tsx; the overlay editor and runtime render elements through these",
    }),
    buildManifest({
        outFile: fileURLToPath(
            new URL("../generated/modules.backend.ts", import.meta.url),
        ),
        file: "backend.ts",
        variable: "b",
        purpose:
            "one static import per <root>/<id>/backend.ts for the compiled binaries (bun build --compile), where the runtime scan cannot reach disk",
    }),
]);
